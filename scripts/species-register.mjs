/**
 * The species register: authored data, one entry per candidate tree.
 *
 * Every figure here is quoted from a published source and carries the source's
 * own wording in `source_text`, because a hardiness number with no provenance is
 * indistinguishable from a guess and this list will be read by someone deciding
 * what to buy. Nothing in this file was measured on the parcel — no bundled
 * source records a single plant growing there.
 *
 * Two conventions matter for reading the numbers:
 *
 * `hardiness.min_c` is the temperature the species is tested against. Where a
 * source states a temperature ("hardy to about −25 °C"), that number is used
 * directly and `derived` is false. Where a source gives only a USDA zone range,
 * the value is the WARM edge of its coldest zone — a "5-9" rating becomes
 * −23.3 °C, the warm end of zone 5, not the −28.9 °C at its cold end — which is
 * the conservative reading of a band, and `derived` is true. The conversion is
 * never silent, and it is always the whole zone: reading "zone 5" as 5a and
 * taking −26.1 °C splits a band the source did not split.
 *
 * `disputed` marks a species whose sources contradict each other or contradict
 * the species' own native range. Those are not averaged into a middle number.
 * A disputed cold rating cannot return a clean pass; it comes back marginal or
 * unknown with the contradiction published, because that is the honest state of
 * the evidence and it tells the reader exactly what to check locally.
 *
 * The drought, soil and exposure verdicts are assigned here from the quoted
 * source text; where a source is silent the verdict is `unknown` and it is
 * listed as untested rather than assumed favourable.
 *
 * A `fruit` block marks an entry as grown for a crop as well as for shade, and
 * it is deliberately separate from the survival fields above. Surviving and
 * cropping are two different questions with two different answers here: a tree
 * can be hardy to −30 °C in January and still lose every flower to −3 °C in
 * April. So `tests`/`verdict` continue to mean "will it live", and the fruit
 * block carries what decides "will it fruit" — when it flowers, whether one
 * tree can set fruit alone, and the bud-kill temperatures where a source
 * publishes them. `bloom_months` is the flowering period as the source states
 * it, not a local observation; nobody has watched a tree flower on this parcel.
 *
 * `client_reported` marks a species the client says already does well in the
 * area. That is worth recording and worth showing, and it is not a source: it
 * cannot answer a test, it cannot upgrade a verdict, and it is rendered as what
 * it is. The register already contains the reason to take it seriously — the
 * Quercus brantii entry is a published figure being wrong about a tree that
 * plainly grows here.
 */

